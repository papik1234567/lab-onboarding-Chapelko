#!/bin/bash

# ============================================================
# ПРАКТИЧЕСКАЯ РАБОТА: АУДИТ КЛИЕНТСКОГО КОМПЬЮТЕРА (macOS)
# Автор: Chapelko
# Назначение: сбор сведений о ПК, проверка базового ПО
#             и выделение потенциально излишнего ПО.
# ============================================================

# ------------------------------------------------------------
# Расположение скрипта и файл отчёта (рядом со скриптом).
# ------------------------------------------------------------
SCRIPT_DIR="$(cd "$(dirname "$0")" && pwd)"
REPORT="$SCRIPT_DIR/pc_report.txt"

# Уникальный временный файл для списка приложений.
APPS_FILE="${TMPDIR:-/tmp}/apps_list_$$.txt"

# Удаление временного файла при любом завершении.
trap 'rm -f "$APPS_FILE"' EXIT
: > "$APPS_FILE"

# ------------------------------------------------------------
# ПОДПРОГРАММА ВЫВОДА (аналог :log из batch).
# Принимает текст, печатает его на экран и в файл отчёта.
# Внутри используется printf, чтобы безопасно обрабатывать
# любые символы (%, !, *, кавычки и т.п.).
# ------------------------------------------------------------
log() {
    printf '%s\n' "$1"
}

# ------------------------------------------------------------
# СЧЁТЧИКИ РЕЗУЛЬТАТОВ.
# ------------------------------------------------------------
CHECKED=0
RECOMMENDATIONS=0
EXCESS_COUNT=0

# ------------------------------------------------------------
# Перенаправляем stdout и stderr одновременно на экран
# и в файл отчёта. Этот блок должен идти ПОСЛЕ определения
# log(), иначе функция попадёт в перенаправление.
# ------------------------------------------------------------
exec > >(tee "$REPORT") 2>&1

# ============================================================
# НАЧАЛО АУДИТА
# ============================================================
log "========================================"
log "       АУДИТ КОМПЬЮТЕРА macOS"
log "========================================"
log ""
log "Дата проверки: $(date '+%d.%m.%Y %H:%M:%S')"
log ""

# ------------------------------------------------------------
# 1. ОПЕРАЦИОННАЯ СИСТЕМА
# ------------------------------------------------------------
log "----------------------------------------"
log "1. ОПЕРАЦИОННАЯ СИСТЕМА"
log "----------------------------------------"

if command -v sw_vers >/dev/null 2>&1; then
    sw_vers
else
    log "Не удалось определить операционную систему."
fi
log ""

# ------------------------------------------------------------
# 2. ПРОЦЕССОР
# Явно очищаем переменную перед сбором значения.
# ------------------------------------------------------------
log "----------------------------------------"
log "2. ПРОЦЕССОР"
log "----------------------------------------"

CPU=""
CPU="$(sysctl -n machdep.cpu.brand_string 2>/dev/null)"

if [[ -z "$CPU" ]]; then
    CPU="$(system_profiler SPHardwareDataType 2>/dev/null |
        awk -F ': ' '/Chip:/ {print $2; exit}')"
fi

if [[ -n "$CPU" ]]; then
    log "Процессор: $CPU"
else
    log "Не удалось определить процессор."
fi
log ""

# ------------------------------------------------------------
# 3. ОПЕРАТИВНАЯ ПАМЯТЬ
# Явно очищаем переменную, проверяем числовое значение.
# ------------------------------------------------------------
log "----------------------------------------"
log "3. ОПЕРАТИВНАЯ ПАМЯТЬ"
log "----------------------------------------"

TOTAL_BYTES=""
TOTAL_BYTES="$(sysctl -n hw.memsize 2>/dev/null)"

if [[ "$TOTAL_BYTES" =~ ^[0-9]+$ ]]; then
    TOTAL_GB=$((TOTAL_BYTES / 1073741824))
    log "Всего памяти: ${TOTAL_GB} ГБ"
else
    log "Не удалось определить объём оперативной памяти."
fi
log ""

# ------------------------------------------------------------
# 4. СИСТЕМНЫЙ ДИСК
# ------------------------------------------------------------
log "----------------------------------------"
log "4. СИСТЕМНЫЙ ДИСК"
log "----------------------------------------"

if df -h / >/dev/null 2>&1; then
    df -h /
else
    log "Не удалось получить информацию о системном диске."
fi
log ""

# ------------------------------------------------------------
# 5. СБОР УСТАНОВЛЕННЫХ ПРИЛОЖЕНИЙ
# Обходим стандартные каталоги macOS. Внутрь .app не заходим
# (-prune), названия сохраняем во временный файл.
# ------------------------------------------------------------
log "----------------------------------------"
log "5. СБОР УСТАНОВЛЕННЫХ ПРОГРАММ"
log "----------------------------------------"
log "Выполняется поиск приложений..."

: > "$APPS_FILE"

for DIR in /Applications "$HOME/Applications" /System/Applications; do
    if [[ -d "$DIR" ]]; then
        find "$DIR" -maxdepth 5 -type d -name "*.app" -prune -print 2>/dev/null |
        while IFS= read -r APP; do
            NAME="$(basename "$APP" .app)"
            if [[ -n "$NAME" ]]; then
                printf '%s\n' "$NAME" >> "$APPS_FILE"
            fi
        done
    fi
done

# Системные компоненты, которые могут быть не видны через find.
if [[ -e "/Applications/Safari.app" ]]; then
    echo "Safari" >> "$APPS_FILE"
fi

if [[ -e "/System/Library/CoreServices/Applications/Archive Utility.app" ]]; then
    echo "Archive Utility" >> "$APPS_FILE"
fi

sort -fu "$APPS_FILE" -o "$APPS_FILE"

APP_COUNT="$(wc -l < "$APPS_FILE" | tr -d ' ')"

log "Найдено приложений: $APP_COUNT"
log ""

if [[ "$APP_COUNT" -gt 0 ]]; then
    # Выводим список построчно через log().
    while IFS= read -r APP_NAME; do
        log "$APP_NAME"
    done < "$APPS_FILE"
else
    log "Список установленных приложений пуст."
fi
log ""

# ============================================================
# ПОДПРОГРАММЫ ПОИСКА
# check_app  — возвращает 0/1 по факту совпадения.
# show_apps  — печатает совпадения через log().
# ============================================================
check_app() {
    grep -Eiq "$1" "$APPS_FILE"
}

show_apps() {
    grep -Ei "$1" "$APPS_FILE" | while IFS= read -r APP_LINE; do
        log "$APP_LINE"
    done
}

# ============================================================
# 6. БАЗОВОЕ ПО
# ============================================================
log "----------------------------------------"
log "6. ПРОВЕРКА БАЗОВОГО ПО"
log "----------------------------------------"
log "Проверяются основные категории программ."
log ""

# --- Офисный пакет -------------------------------------------------
CHECKED=$((CHECKED + 1))
log "[ОФИСНЫЕ ПРОГРАММЫ]"
PATTERN_OFFICE="Microsoft Word|Microsoft Excel|Microsoft PowerPoint|LibreOffice|OpenOffice|Pages|Numbers|Keynote|МойОфис|WPS Office|wpsoffice"

if check_app "$PATTERN_OFFICE"; then
    log "Требование выполнено:"
    show_apps "$PATTERN_OFFICE"
else
    log "Рекомендация: установить офисный пакет, например LibreOffice или Microsoft Office."
    RECOMMENDATIONS=$((RECOMMENDATIONS + 1))
fi
log ""

# --- Браузер -------------------------------------------------------
CHECKED=$((CHECKED + 1))
log "[БРАУЗЕРЫ]"
PATTERN_BROWSER="Safari|Google Chrome|Firefox|Microsoft Edge|Brave|Opera|Яндекс"

if check_app "$PATTERN_BROWSER"; then
    log "Требование выполнено:"
    show_apps "$PATTERN_BROWSER"
    log "Примечание: Safari является системным компонентом macOS,"
    log "его наличие не доказывает, что рабочее место настроено."
else
    log "Рекомендация: установить браузер Safari, Chrome или Firefox."
    RECOMMENDATIONS=$((RECOMMENDATIONS + 1))
fi
log ""

# --- PDF -----------------------------------------------------------
CHECKED=$((CHECKED + 1))
log "[ЧТЕНИЕ PDF]"
PATTERN_PDF="Preview|Adobe Acrobat|Foxit|Skim|PDF Expert"

if check_app "$PATTERN_PDF"; then
    log "Требование выполнено:"
    show_apps "$PATTERN_PDF"
    log "Примечание: Preview является системным компонентом macOS."
else
    log "Рекомендация: установить программу для работы с PDF."
    RECOMMENDATIONS=$((RECOMMENDATIONS + 1))
fi
log ""

# --- Архиватор -----------------------------------------------------
CHECKED=$((CHECKED + 1))
log "[АРХИВАТОРЫ]"
PATTERN_ARCH="Archive Utility|Keka|The Unarchiver|BetterZip|7-Zip|WinRAR"

if check_app "$PATTERN_ARCH"; then
    log "Требование выполнено:"
    show_apps "$PATTERN_ARCH"
    log "Примечание: Archive Utility является системным компонентом macOS."
else
    log "Рекомендация: установить архиватор, например Keka или The Unarchiver."
    RECOMMENDATIONS=$((RECOMMENDATIONS + 1))
fi
log ""

# --- Антивирус -----------------------------------------------------
CHECKED=$((CHECKED + 1))
log "[АНТИВИРУСНАЯ ЗАЩИТА]"
PATTERN_AV="Malwarebytes|Bitdefender|Avast|ESET|Norton|Sophos|Dr.Web|Kaspersky"

if check_app "$PATTERN_AV"; then
    log "Обнаружена дополнительная защитная программа:"
    show_apps "$PATTERN_AV"
else
    log "Сторонний антивирус не обнаружен."
    log "macOS имеет встроенные механизмы защиты, включая XProtect и Gatekeeper."
    log "Необходимость дополнительной защиты определяется политикой организации."
fi
log ""

# ============================================================
# 7. ИЗЛИШНЕЕ ПО
# ============================================================
log "----------------------------------------"
log "7. ПРОВЕРКА ИЗЛИШНЕГО ПО"
log "----------------------------------------"
log "Найденные программы не предлагается удалять автоматически."
log "Формулировка носит проверяющий характер: программа не относится"
log "к базовым офисным задачам и подлежит проверке администратором."
log ""

# --- Игровое ПО ----------------------------------------------------
log "[ИГРОВОЕ ПО]"
PATTERN_GAME="Steam|Epic Games|GOG Galaxy|Origin|Ubisoft Connect|Battle.net|Riot Client|Gacha Life|game|gaming"

if check_app "$PATTERN_GAME"; then
    log "Обнаружены программы, требующие проверки:"
    show_apps "$PATTERN_GAME"
    EXCESS_COUNT=$((EXCESS_COUNT + 1))
else
    log "Игровые программы не обнаружены."
fi
log ""

# --- Торрент-клиенты ----------------------------------------------
log "[ТОРРЕНТ-КЛИЕНТЫ]"
PATTERN_TOR="uTorrent|BitTorrent|qBittorrent|Vuze|Transmission|torrent"

if check_app "$PATTERN_TOR"; then
    log "Обнаружены программы, требующие проверки:"
    show_apps "$PATTERN_TOR"
    log "Примечание: торрент-клиенты создают сетевую нагрузку и могут"
    log "быть источником нежелательного ПО."
    EXCESS_COUNT=$((EXCESS_COUNT + 1))
else
    log "Торрент-клиенты не обнаружены."
fi
log ""

# --- Мессенджеры ---------------------------------------------------
log "[МЕССЕНДЖЕРЫ И ЛИЧНОЕ ОБЩЕНИЕ]"
PATTERN_MSG="Discord|Telegram|WhatsApp|Viber|Skype"

if check_app "$PATTERN_MSG"; then
    log "Обнаружены программы, требующие проверки:"
    show_apps "$PATTERN_MSG"
    log "Примечание: в некоторых организациях Telegram или Skype"
    log "являются рабочим инструментом. Требуется уточнение."
    EXCESS_COUNT=$((EXCESS_COUNT + 1))
else
    log "Дополнительные мессенджеры не обнаружены."
fi
log ""

# --- Развлечения ---------------------------------------------------
log "[РАЗВЛЕКАТЕЛЬНЫЕ ПРОГРАММЫ]"
PATTERN_ENT="OBS|Soundpad|Wallpaper Engine|VLC|IINA|FL Studio|Gacha Life|iMovie|Music|TV"

if check_app "$PATTERN_ENT"; then
    log "Обнаружены программы, требующие проверки:"
    show_apps "$PATTERN_ENT"
    log "Примечание: Music и TV являются системными компонентами macOS."
    EXCESS_COUNT=$((EXCESS_COUNT + 1))
else
    log "Развлекательные программы не обнаружены."
fi
log ""

# ============================================================
# 8. ИТОГИ
# ============================================================
log "========================================"
log "8. ИТОГИ АУДИТА"
log "========================================"
log "Проверено категорий базового ПО: $CHECKED"
log "Количество рекомендаций по базовому ПО: $RECOMMENDATIONS"
log "Категорий с потенциально излишним ПО: $EXCESS_COUNT"
log "Найдено установленных приложений: $APP_COUNT"
log ""
log "ВАЖНО:"
log "Вывод скрипта является рекомендацией к проверке, а не"
log "указанием к удалению. Часть программ может быть установлена"
log "по согласованию с руководством или использоваться для"
log "специфических задач. Решение принимает человек, скрипт только"
log "сужает область для просмотра."
log ""
log "Отчёт сохранён:"
log "$REPORT"
log ""
log "========================================"
log "          АУДИТ ЗАВЕРШЁН"
log "========================================"

# ------------------------------------------------------------
# Пауза, чтобы окно не закрывалось при запуске двойным кликом.
# ------------------------------------------------------------
if [[ -t 0 ]]; then
    read -r -p "Нажмите Enter для выхода..." _
fi